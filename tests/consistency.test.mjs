for (const [id, skillId, idx, expected, label] of CASES) {
  test('数据一致性 ' + id + ' ' + skillId + '[' + idx + '] = ' + expected + ' (' + label + ')', () => {
    const params = skillMaxParams(loadChar(id), skillId);
    assert.ok(idx < params.length, '参数下标越界: ' + skillId + ' 只有 ' + params.length + ' 个参数');
    assert.ok(Math.abs(params[idx] - expected) < 1e-9,
      '站点数据为 ' + params[idx] + '，引擎写的是 ' + expected);
  });
}

test('角色基础属性与站点一致', () => {
  const expect = { '1506': [388.1, 1047.8, 654.9, 110], '1501': [640.3, 1047.8, 460.8, 107],
                   '1503': [465.7, 1203.0, 727.7, 99], '1511': [679.1, 1047.8, 509.4, 94] };
  for (const id of Object.keys(expect)) {
    const c = loadChar(id);
    const last = c.stats[c.stats.length - 1];
    assert.equal(last.atk, expect[id][0], id + ' 攻击力');
    assert.equal(last.hp, expect[id][1], id + ' 生命值');
    assert.equal(last.def, expect[id][2], id + ' 防御力');
    assert.equal(last.speed, expect[id][3], id + ' 速度');
  }
});
