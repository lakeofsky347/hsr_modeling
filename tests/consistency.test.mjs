const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const NORM = join(ROOT, 'data', 'nanoka', 'normalized');

function loadChar(id) {
  const f = readdirSync(NORM).find((x) => x.startsWith(id + '_'));
  return JSON.parse(readFileSync(join(NORM, f), 'utf8'));
}
function skillMaxParams(char, skillId) {
  const s = char.skills.find((x) => String(x.id) === String(skillId));
  assert.ok(s, '找不到技能 ' + skillId);
  return s.levels[s.levels.length - 1].params;
}

